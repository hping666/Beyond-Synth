"""Shared SDC generation (docs/spec/01-eval-service.md, config: constraints).

One convention for every tool and rung: the OpenSTA-native text (`all_inputs -no_clocks`, values in ns) is what
Yosys/OpenSTA and ORFS read; the DC/PT copy is produced by dc_sdc(): the `-no_clocks` call is replaced by the
sdc_compat.tcl command (eda-knowledge/05-traps.md #2) and every time value is scaled to the library's time unit
(ASAP7 Liberty uses ps, #10). A design without a clock port gets a virtual clock so that IO delays still apply.
A design with several clock ports (Phase 1 inventory tag `multi_clock`) gets one clock per port, all with the same
period (`clk`, `clk_2`, ...); IO delays are relative to the first. Such designs are inventoried and trial-synthesized
but excluded from the search sets (DECISIONS 2026-09-12).
"""
import re


def clock_ports(clk_port):
    """Normalise the clock-port argument: None / '' -> [], 'clk' -> ['clk'], 'a b' -> ['a', 'b'], list -> list."""
    if not clk_port:
        return []
    if isinstance(clk_port, (list, tuple)):
        return [str(p) for p in clk_port if p]
    return str(clk_port).split()


def opensta_sdc(top, clk_port, period_ns, cfg, lib):
    c = cfg["constraints"]
    clk = c["clock_name"]
    io = float(period_ns) * float(c["io_delay_frac"])
    drv = c["driving_cell"][lib]
    ports = clock_ports(clk_port)
    lines = [f"# generated by src/eval/sdc.py  top={top} lib={lib} period={period_ns:g} ns  (config: constraints)",
             f"current_design {top}"]
    if ports:
        for i, p in enumerate(ports):
            name = clk if i == 0 else f"{clk}_{i + 1}"
            lines.append(f"create_clock -name {name} -period {float(period_ns):g} [get_ports {p}]")
    else:
        lines.append(f"create_clock -name {clk} -period {float(period_ns):g}")
    # a design without non-clock inputs (RTLLM clkgenerator) must not apply input constraints to an empty list (CMD-036);
    # `llength` is the OpenSTA form, dc_sdc() rewrites it to `sizeof_collection` for DC / PrimeTime
    lines += ["set non_clk [all_inputs -no_clocks]",
              "if {[llength $non_clk] > 0} {",
              f"  set_input_delay {io:g} -clock {clk} $non_clk",
              f"  set_driving_cell -lib_cell {drv} $non_clk",
              "}",
              f"set_output_delay {io:g} -clock {clk} [all_outputs]",
              f"set_max_fanout {int(c['max_fanout'])} [current_design]"]
    if c.get("output_load"):
        lines.append(f"set_load {float(c['output_load']):g} [all_outputs]")
    return "\n".join(lines) + "\n"


_TIME_ARGS = re.compile(r"((?:-period|set_input_delay|set_output_delay|-max_delay|-min_delay|-setup|-hold)\s+)(-?[\d.]+(?:[eE][-+]?\d+)?)")


def dc_sdc(text, time_scale=1.0):
    """Rewrite an OpenSTA-native SDC for Synopsys tools (sdc_compat.tcl must be sourced first)."""
    out = text.replace("all_inputs -no_clocks", "snps_all_inputs_no_clocks").replace("[llength $non_clk]", "[sizeof_collection $non_clk]")
    if abs(float(time_scale) - 1.0) > 1e-9:
        out = _TIME_ARGS.sub(lambda m: m.group(1) + f"{float(m.group(2)) * float(time_scale):g}", out)
    return "# rewritten for Synopsys tools by src/eval/sdc.py (time_scale=%g)\n" % float(time_scale) + out
